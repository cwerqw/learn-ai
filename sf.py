import pandas as pd  # 导入 pandas 库，并取别名叫 pd（注意：这里必须是 pandas，不是你的文件名）
import os  # 导入系统模块，用来在电脑上自动创建文件夹

# 1. 自动在D盘创建一个叫“代码练习”的文件夹（如果已经有了也不会报错）
文件夹路径 = 'D:/代码练习'
os.makedirs(文件夹路径, exist_ok=True)
print(f"✅ 文件夹已准备好：{文件夹路径}")

# 2. 用代码造一个表格（解决没表格的问题）
数据 = pd.DataFrame({
    '姓名': ['叶问', '李小龙', '孙兴华', '郭靖', '黄蓉'],
    '年龄': [30, 25, 22, 40, 35],
    '城市': ['佛山', '香港', '北京', '襄阳', '襄阳'],
    '分数': [88, 92, 85, 78, 95]
})
# 1. 先复制一份原数据，避免修改原表
读取数据 = 数据.copy()

# 2. 插入“序列”列，自动生成 1 到 5 的编号
读取数据.insert(0, '序列', range(1, len(读取数据) + 1))

# 3. 将“序列”列设为索引
读取数据.set_index('序列', inplace=True)

# 4. 打印结果看看
读取数据.loc[读取数据['城市']=='襄阳','称呼']='先生'
print(读取数据)
